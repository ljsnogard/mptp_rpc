//! RPC interface 描述聚合在一个路径下的一组 RPC 服务，该组 RPC 服务拥有
//! 共同的由 interface 规定的子路由器规则。
//!
//! 一个 RPC 路径只由 **interface + service** 组成，方法名不出现在路径上：
//!
//! ```text
//! /{interface}/{service}
//! ```
//!
//! interface 的路径由用户手写（或由 `#[rpc(path = "...")]` 宏生成）；service 的路径
//! 由 `#[rpc(service = "...")]` 注入 trait 的关联常量 [`TrRpcInterface::PATH`] 同级的
//! `SERVICE_PATH`。客户端只持有一个 `MptpClient`，interface 由零大小类型参数携带。
//!
//! # `interface_`: interface description and path composition
//!
//! An RPC path is `/{interface}/{service}`; the method name never appears on the wire.
//! The interface path is user-written (or generated by the interface macro), while the
//! service path is injected into the service trait by the service macro.

/// 一段稳定的 RPC interface 路径前缀。
///
/// `PATH` **不含**首尾 `/`；与服务路径拼接时由 [`concat_location`] 统一规范化。
///
/// # Examples
///
/// ```
/// use rpc_core_v1::messaging::TrRpcInterface;
///
/// struct ApiV1;
///
/// impl TrRpcInterface for ApiV1 {
///     const PATH: &'static str = "api/v1";
/// }
///
/// assert_eq!(ApiV1::PATH, "api/v1");
/// ```
pub trait TrRpcInterface {
    /// 不含首尾 `/` 的 interface 前缀。
    const PATH: &'static str;
}

/// 拼出 `/{interface}/{service}`，并消掉两端多余的首尾斜杠。
///
/// 该方法只做**段边界**上的规范化：连续 `/` 不会被折叠，空段也不会被删除——注册与
/// 匹配两侧都依赖同一套段规则，隐藏的折叠会让线上路径与注册路径对不上。
///
/// # Examples
///
/// ```
/// use rpc_core_v1::messaging::concat_location;
///
/// assert_eq!(concat_location("api/v1", "customer/goods"), "/api/v1/customer/goods");
/// assert_eq!(concat_location("/api/v1/", "/customer/goods/"), "/api/v1/customer/goods");
/// ```
pub fn concat_location(interface: &str, service: &str) -> String {
    let interface = interface.trim_matches('/');
    let service = service.trim_matches('/');
    match (interface.is_empty(), service.is_empty()) {
        (true, true) => "/".to_string(),
        (true, false) => format!("/{service}"),
        (false, true) => format!("/{interface}/"),
        (false, false) => format!("/{interface}/{service}"),
    }
}

#[cfg(test)]
mod tests_ {
    use super::*;

    /// 测试 interface + service 路径拼接会消掉多余的首尾斜杠。
    /// Test that interface + service composition normalises surrounding slashes.
    ///
    /// - 手段：分别用带斜杠与不带斜杠的两组参数调用 `location`，再测空 interface。
    /// - 判断：前两次都得到 `/api/v1/workspace`；空 interface 得到 `/workspace`。
    ///
    /// - Means: call `location` with slashed, unslashed and empty interfaces.
    /// - Verdict: the first two produce `/api/v1/workspace`; the empty one `/workspace`.
    #[test]
    fn location_normalises_slashes_() {
        assert_eq!(concat_location("api/v1", "workspace"), "/api/v1/workspace");
        assert_eq!(concat_location("/api/v1/", "/workspace/"), "/api/v1/workspace");
        assert_eq!(concat_location("", "workspace"), "/workspace");
    }
}
